"use server";

import { revalidatePath } from "next/cache";
import { prisma } from "@/server/db/client";
import { requireAdmin } from "@/server/auth/guards";
import {
  analyzeSymbol,
  loadEngineSettings,
  scoreCandidate,
} from "@/server/modules/signal-engine/engine";
import { getDemoCandles } from "@/server/modules/market-data/demo-provider";
import { getFinnhubCandles } from "@/server/modules/market-data/finnhub-provider";

export async function runEngineAction(): Promise<void> {
  const session = await requireAdmin();
  const settings = await loadEngineSettings();
  const useLive = Boolean(process.env.FINNHUB_API_KEY);

  const run = await prisma.signalEngineRun.create({
    data: {
      status: "RUNNING",
      provider: useLive ? "FINNHUB" : "DEMO",
      params: settings as never,
    },
  });

  const symbols = await prisma.symbol.findMany({ where: { isActive: true } });

  const datasets = await Promise.all(
    symbols.map(async (symbol) => {
      if (useLive) {
        try {
          const candles = await getFinnhubCandles(symbol.symbol);
          return { symbol, candles };
        } catch {
          return { symbol, candles: getDemoCandles(symbol.symbol) };
        }
      }
      return { symbol, candles: getDemoCandles(symbol.symbol) };
    })
  );

  let pending = 0;
  let rejected = 0;

  for (const { symbol, candles } of datasets) {
    const raw = analyzeSymbol(symbol.id, candles);
    const scored = scoreCandidate(raw, settings);

    await prisma.marketAnalysis.create({
      data: {
        symbolId: symbol.id,
        timeframe: "H1",
        runAt: new Date(),
        closePrice: scored.analysis.close,
        ema50: scored.analysis.ema50,
        ema200: scored.analysis.ema200,
        rsi14: scored.analysis.rsi14,
        atr14: scored.analysis.atr14,
        marketStructure: scored.analysis.structure,
        supportLevels: scored.analysis.supports as never,
        resistanceLevels: scored.analysis.resistances as never,
        notes: useLive
          ? `Live Finnhub H1 data for ${symbol.symbol}`
          : `DEMO DATA run for ${symbol.symbol}`,
      },
    });

    const status = scored.rejectionReasons.length
      ? "REJECTED"
      : "PENDING_REVIEW";
    if (status === "REJECTED") rejected += 1;
    else pending += 1;

    await prisma.signalEngineCandidate.create({
      data: {
        engineRunId: run.id,
        symbolId: symbol.id,
        timeframe: "H1",
        direction: scored.direction,
        entryPrice: scored.entry,
        stopLossPrice: scored.stopLoss,
        tp1Price: scored.tp1,
        tp2Price: scored.tp2,
        qualityScore: scored.qualityScore,
        qualityLabel: scored.qualityLabel,
        factors: scored.factors as never,
        rejectionReasons: scored.rejectionReasons as never,
        status,
      },
    });
  }

  await prisma.signalEngineRun.update({
    where: { id: run.id },
    data: {
      status: "SUCCESS",
      finishedAt: new Date(),
      candidatesCount: symbols.length,
      noTradeCount: rejected,
      publishedCount: 0,
    },
  });

  void session;
  revalidatePath("/admin/engine");
}

export async function approveCandidate(formData: FormData): Promise<void> {
  const session = await requireAdmin();
  const id = formData.get("id") as string | null;
  if (!id) return;

  const candidate = await prisma.signalEngineCandidate.findUnique({
    where: { id },
    include: { symbol: true },
  });
  if (!candidate || candidate.status !== "PENDING_REVIEW") return;

  const count = await prisma.signal.count();
  const signalCode = `SIG-${new Date().getFullYear()}-${String(
    count + 1
  ).padStart(4, "0")}`;

  const signal = await prisma.signal.create({
    data: {
      signalCode,
      symbolId: candidate.symbolId,
      direction: candidate.direction,
      timeframe: candidate.timeframe,
      marketSession: "GLOBAL",
      entryPrice: candidate.entryPrice!,
      stopLossPrice: candidate.stopLossPrice!,
      tp1Price: candidate.tp1Price!,
      tp2Price: candidate.tp2Price,
      riskLevel: "MEDIUM",
      qualityScore: candidate.qualityScore,
      qualityLabel: candidate.qualityLabel,
      analysisMd: `Engine analysis: ${candidate.symbol.displayName} ${candidate.direction}. Quality ${candidate.qualityScore}/100.`,
      reasoningMd: `Generated by the signal engine. Factors: ${JSON.stringify(
        candidate.factors
      )}. Always verify manually before publishing.`,
      status: "DRAFT",
      source: "ENGINE",
      engineRunId: candidate.engineRunId,
      accessTier: "PREMIUM",
      createdById: session.user.id,
    },
  });

  await prisma.signalEngineCandidate.update({
    where: { id },
    data: { status: "APPROVED", signalId: signal.id },
  });

  revalidatePath("/admin/engine");
  revalidatePath("/admin/signals");
}

export async function discardCandidate(formData: FormData): Promise<void> {
  await requireAdmin();
  const id = formData.get("id") as string | null;
  if (!id) return;

  await prisma.signalEngineCandidate.update({
    where: { id },
    data: { status: "DISCARDED" },
  });

  revalidatePath("/admin/engine");
}